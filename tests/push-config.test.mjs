import test from 'node:test';
import assert from 'node:assert/strict';
import { copyFileSync, mkdirSync, mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { resolvePushConfig } = require('../plugins/push-config.cjs');
const plist = require('@expo/plist').default;

test('enables push only for both matching client registrations, rejects the old app and server keys', t => {
  const root = mkdtempSync(join(tmpdir(), 'bayshop-push-config-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const app = 'com.bayshop.mobile.demo';
  const project = 'baymd-148208';
  const sender = '376156188250';
  const env = { BAYSHOP_FIREBASE_ANDROID_CONFIG: 'client.json', BAYSHOP_FIREBASE_IOS_CONFIG: 'client.plist' };
  const android = { project_info: { project_id: project, project_number: sender }, client: [{ client_info: { android_client_info: { package_name: app }, mobilesdk_app_id: 'unit-test' }, api_key: [{ current_key: 'unit-test-public' }] }] };
  const ios = { PROJECT_ID: project, GCM_SENDER_ID: sender, BUNDLE_ID: app, GOOGLE_APP_ID: 'unit-test', API_KEY: 'unit-test-public' };
  const save = (data, apple) => { writeFileSync(join(root, 'client.json'), JSON.stringify(data)); writeFileSync(join(root, 'client.plist'), plist.build(apple)); };
  save(android, ios);
  assert.equal(resolvePushConfig(env, root).enabled, true);
  assert.equal(resolvePushConfig({}, root).enabled, false);
  assert.throws(() => resolvePushConfig({ BAYSHOP_REQUIRE_PUSH: '1' }, root));
  const localDir = join(root, 'credentials/firebase');
  mkdirSync(localDir, { recursive: true });
  copyFileSync(join(root, 'client.json'), join(localDir, 'google-services.json'));
  assert.throws(() => resolvePushConfig({ BAYSHOP_REQUIRE_PUSH: '1' }, root), /both Android and iOS/);
  copyFileSync(join(root, 'client.plist'), join(localDir, 'GoogleService-Info.plist'));
  assert.equal(resolvePushConfig({ BAYSHOP_REQUIRE_PUSH: '1' }, root).enabled, true);
  assert.throws(() => resolvePushConfig({ BAYSHOP_REQUIRE_PUSH: '1', EAS_BUILD: 'true' }, root), /Both BayShop/);
  assert.throws(() => resolvePushConfig({ ...env, BAYSHOP_FIREBASE_IOS_CONFIG: '' }, root), /both Android and iOS/);
  assert.equal(resolvePushConfig({ ...env, EAS_BUILD: 'true' }, root).androidPath, join(root, 'client.json'));
  save(android, { ...ios, BUNDLE_ID: 'com.bayshop.BayShop-MF' });
  assert.throws(() => resolvePushConfig(env, root));
  save({ ...android, project_info: { project_id: 'other', project_number: sender } }, ios);
  assert.throws(() => resolvePushConfig(env, root));
  save({ ...android, type: 'service_account', private_key: 'synthetic' }, ios);
  assert.throws(() => resolvePushConfig(env, root), /Server credentials/);
});
